/** Extract env var references from source content based on language patterns. */
function extractEnvVarReferences(
  content: string,
  language: string,
): Array<{ name: string; hasDefault: boolean }> {
  const refs: Array<{ name: string; hasDefault: boolean }> = [];
  const seen = new Set<string>();

  // JavaScript/TypeScript: process.env.VAR_NAME
  if (language === "typescript" || language === "javascript" || language === "unknown") {
    const processEnvRegex = /process\.env\.([A-Z_][A-Z0-9_]*)/g;
    let match: RegExpExecArray | null;
    while ((match = processEnvRegex.exec(content)) !== null) {
      const name = match[1];
      if (name && !seen.has(name)) {
        seen.add(name);
        // Check for default: process.env.X || "default" or process.env.X ?? "default"
        const afterMatch = content.slice(
          (match.index ?? 0) + match[0].length,
          (match.index ?? 0) + match[0].length + 30,
        );
        const hasDefault = /^\s*(\?\?|\|\|)\s*["'`\d]/.test(afterMatch);
        refs.push({ name, hasDefault });
      }
    }

    // Also check process.env["VAR_NAME"] / process.env['VAR_NAME']
    const bracketRegex = /process\.env\[["']([A-Z_][A-Z0-9_]*)["']\]/g;
    while ((match = bracketRegex.exec(content)) !== null) {
      const name = match[1];
      if (name && !seen.has(name)) {
        seen.add(name);
        const afterMatch = content.slice(
          (match.index ?? 0) + match[0].length,
          (match.index ?? 0) + match[0].length + 30,
        );
        const hasDefault = /^\s*(\?\?|\|\|)\s*["'`\d]/.test(afterMatch);
        refs.push({ name, hasDefault });
      }
    }
  }

  // Python: os.environ["VAR"], os.environ.get("VAR"), os.getenv("VAR")
  if (language === "python") {
    const pyRegex = /os\.(?:environ\[["']|environ\.get\(["']|getenv\(["'])([A-Z_][A-Z0-9_]*)/g;
    let match: RegExpExecArray | null;
    while ((match = pyRegex.exec(content)) !== null) {
      const name = match[1];
      if (name && !seen.has(name)) {
        seen.add(name);
        // os.environ.get("X", "default") or os.getenv("X", "default") have defaults
        const hasDefault =
          /\.get\(|getenv\(/.test(match[0]) &&
          /,\s*["'\d]/.test(
            content.slice(
              (match.index ?? 0) + match[0].length,
              (match.index ?? 0) + match[0].length + 30,
            ),
          );
        refs.push({ name, hasDefault });
      }
    }
  }

  // Go: os.Getenv("VAR")
  if (language === "go") {
    const goRegex = /os\.Getenv\("([A-Z_][A-Z0-9_]*)"\)/g;
    let match: RegExpExecArray | null;
    while ((match = goRegex.exec(content)) !== null) {
      const name = match[1];
      if (name && !seen.has(name)) {
        seen.add(name);
        refs.push({ name, hasDefault: false });
      }
    }
  }

  return refs;
}

