interface DiscoveredFile {
  path: string;
  size: number;
  lineCount: number;
}

/** Result of additionality analysis for a single context file */
interface AdditionalityResult {
  redundancyPct: number; // 0-100, one decimal
  additionalityPct: number; // 0-100, one decimal
  duplicateLines: Array<{ line: number; text: string; matchedIn: string }>;
  additiveLines: Array<{ line: number; text: string }>;
  methodology: string;
}

/**
 * Strip markdown formatting to extract plain text for comparison.
 * Removes code fences, headings markers, links, images, bold/italic markers.
 */
function normalizeForComparison(text: string): string {
  return (
    text
      // Remove code blocks entirely (content inside fences is not prose)
      .replace(/```[\s\S]*?```/g, "")
      // Remove inline code
      .replace(/`[^`]+`/g, "")
      // Remove markdown headings markers
      .replace(/^#{1,6}\s+/gm, "")
      // Remove link syntax but keep text: [text](url) → text
      .replace(/\[([^\]]*)\]\([^)]*\)/g, "$1")
      // Remove image syntax
      .replace(/!\[([^\]]*)\]\([^)]*\)/g, "")
      // Remove bold/italic markers
      .replace(/[*_]{1,3}([^*_]+)[*_]{1,3}/g, "$1")
      // Remove HTML tags (loop to handle nested/malformed tags like <<script>)
      .replace(/<[^>]+>/g, "")
      .replace(/<[^>]+>/g, "")
      // Remove any remaining lone angle brackets left after tag stripping
      .replace(/[<>]/g, "")
      // Collapse whitespace
      .replace(/\s+/g, " ")
      .trim()
  );
}

/**
 * Split text into meaningful sentences/segments for comparison.
 * Returns non-empty segments of at least 5 words.
 */
function splitSegments(text: string): string[] {
  // Split on sentence boundaries (period, newline) and list items
  const raw = text.split(/[.\n]+/).map((s) => s.trim());
  // Filter out very short segments (< 5 words) to avoid false positive matches
  return raw.filter((s) => s.split(/\s+/).length >= 5);
}

/**
 * Compute Jaccard similarity between two word sets.
 * Returns value 0-1.
 */
function jaccardSimilarity(a: string, b: string): number {
  const wordsA = new Set(a.toLowerCase().split(/\s+/));
  const wordsB = new Set(b.toLowerCase().split(/\s+/));
  let intersection = 0;
  for (const w of wordsA) {
    if (wordsB.has(w)) intersection++;
  }
  const union = wordsA.size + wordsB.size - intersection;
  if (union === 0) return 0;
  return intersection / union;
}

/**
 * Compute additionality for a context file against reference documents.
 * Uses sentence-level Jaccard similarity to identify duplicated content.
 */
function computeAdditionality(
  contextContent: string,
  contextPath: string,
  referenceDocs: Array<{ path: string; content: string }>,
): AdditionalityResult {
  const normalizedContext = normalizeForComparison(contextContent);
  const contextSegments = splitSegments(normalizedContext);

  // Pre-compute reference segments
  const refSegments: Array<{ segment: string; path: string }> = [];
  for (const doc of referenceDocs) {
    const normalized = normalizeForComparison(doc.content);
    for (const seg of splitSegments(normalized)) {
      refSegments.push({ segment: seg, path: doc.path });
    }
  }

  // Map original lines to their comparison status
  const lines = contextContent.split("\n");
  const duplicateLines: AdditionalityResult["duplicateLines"] = [];
  const additiveLines: AdditionalityResult["additiveLines"] = [];

  // Track per-segment match status
  let matchedSegments = 0;
  const totalSegments = contextSegments.length;

  const SIMILARITY_THRESHOLD = 0.6;

  for (const segment of contextSegments) {
    let bestMatch = 0;
    let bestMatchPath = "";
    for (const ref of refSegments) {
      const sim = jaccardSimilarity(segment, ref.segment);
      if (sim > bestMatch) {
        bestMatch = sim;
        bestMatchPath = ref.path;
      }
    }
    if (bestMatch >= SIMILARITY_THRESHOLD) {
      matchedSegments++;
      // Find the original line that best corresponds to this segment
      const segWords = segment.toLowerCase();
      for (let i = 0; i < lines.length; i++) {
        const line = lines[i] ?? "";
        const lineLower = line.toLowerCase().trim();
        if (
          lineLower.length >= 10 &&
          segWords.includes(lineLower.replace(/[#*_`()[\]]/g, "").trim())
        ) {
          if (!duplicateLines.some((d) => d.line === i + 1)) {
            duplicateLines.push({ line: i + 1, text: line.trim(), matchedIn: bestMatchPath });
          }
          break;
        }
      }
    }
  }

  // Identify additive lines (non-empty, non-duplicate, meaningful)
  const dupLineNums = new Set(duplicateLines.map((d) => d.line));
  for (let i = 0; i < lines.length; i++) {
    const trimmed = (lines[i] ?? "").trim();
    if (trimmed.length >= 10 && !dupLineNums.has(i + 1)) {
      // Skip pure markdown formatting lines
      if (!/^(#{1,6}\s*$|```|---|\*\*\*|___|\|)/.test(trimmed)) {
        additiveLines.push({ line: i + 1, text: trimmed });
      }
    }
  }

  const redundancyPct =
    totalSegments > 0 ? Math.round((matchedSegments / totalSegments) * 1000) / 10 : 0;
  const additionalityPct = Math.round((100 - redundancyPct) * 10) / 10;

  const methodology = [
    `Sentence-level Jaccard similarity (threshold ≥ ${SIMILARITY_THRESHOLD}).`,
    `Compared ${totalSegments} segments from ${contextPath}`,
    `against ${refSegments.length} segments from ${referenceDocs.map((d) => d.path).join(", ")}.`,
    `${matchedSegments}/${totalSegments} segments matched as duplicative.`,
  ].join(" ");

  return { redundancyPct, additionalityPct, duplicateLines, additiveLines, methodology };
}

/**
 * Check if critical information is front-loaded in the first 20% of a file.
 * Returns true if critical info is found only in the bottom 80%.
 */
function hasBuriedCriticalInfo(content: string): boolean {
  const lines = content.split("\n");
  const cutoff = Math.max(1, Math.ceil(lines.length * 0.2));
  const topSection = lines.slice(0, cutoff).join("\n");
  const bottomSection = lines.slice(cutoff).join("\n");

  // Check if critical info exists in bottom but NOT in top
  const topHasCritical = CRITICAL_INFO_PATTERNS.some((p) => p.test(topSection));
  const bottomHasCritical = CRITICAL_INFO_PATTERNS.some((p) => p.test(bottomSection));

  return !topHasCritical && bottomHasCritical;
}

/**
 * Extract file/directory path references from content.
 * Looks for patterns like `path/to/file.ts`, `./src/`, `packages/foo/`, etc.
 */
function extractReferencedPaths(content: string): string[] {
  const pathPattern = /(?:^|\s|`|")((?:\.\/|\.\.\/)?(?:[a-zA-Z0-9_-]+\/)+[a-zA-Z0-9_.-]*)/gm;
  const paths: string[] = [];
  let match: RegExpExecArray | null;
  while ((match = pathPattern.exec(content)) !== null) {
    const p = match[1]?.replace(/^\.\//, "");
    // Filter out common non-path matches
    if (p && !p.startsWith("http") && !p.startsWith("//")) {
      paths.push(p);
    }
  }
  return paths;
}

/**
 * Check if content appears to be auto-generated boilerplate without project specifics.
 */
function isLikelyBoilerplate(content: string, repoFiles: readonly string[]): boolean {
  // Check for boilerplate patterns
  const hasBoilerplateMarkers = BOILERPLATE_PATTERNS.some((p) => p.test(content));

  // Check if content references any actual repo files/directories
  const repoFilenames = new Set<string>();
  for (const f of repoFiles) {
    // Add both full path and filename parts
    const parts = f.split("/");
    for (const part of parts) {
      if (part && part.length > 2 && !part.startsWith(".")) {
        repoFilenames.add(part);
      }
    }
  }

  // Count project-specific references
  let specificRefs = 0;
  for (const name of repoFilenames) {
    if (content.includes(name)) {
      specificRefs++;
    }
  }

  // Consider it boilerplate if it has boilerplate markers AND few project-specific references
  return hasBoilerplateMarkers && specificRefs < 2;
}

export const contextQualityAnalyzer: PillarAnalyzer = {
  pillar: PILLAR,
  name: PILLAR_NAMES[PILLAR],
  version: "0.2.0",

  async supports(): Promise<boolean> {
    return true;
  },

  async analyze(context: RepoContext) {
    const findings: Finding[] = [];
    let score = 20; // Baseline: no context files = 20%

    const discoveredFiles: DiscoveredFile[] = [];
    const foundContextFiles: string[] = [];

    // Check standard context files
    for (const cf of CONTEXT_FILES) {
      const exists = await context.fileExists(cf);
      if (exists) {
        foundContextFiles.push(cf);
        const content = await context.readFile(cf);
        if (content !== null) {
          discoveredFiles.push({
            path: cf,
            size: content.length,
            lineCount: content.split("\n").length,
          });
        }
      }
    }

    // Check directory patterns
    for (const dir of CONTEXT_DIRS) {
      const hasFiles = context.files.some((f) => f.startsWith(dir + "/"));
      if (hasFiles) {
        const dirLabel = dir + "/";
        foundContextFiles.push(dirLabel);
        discoveredFiles.push({ path: dirLabel, size: 0, lineCount: 0 });
      }
    }

    // Discover nested AGENTS.md files for monorepos
    const nestedAgentsFiles = context.files.filter(
      (f) => f !== "AGENTS.md" && f.endsWith("/AGENTS.md"),
    );
    for (const nestedFile of nestedAgentsFiles) {
      if (!foundContextFiles.includes(nestedFile)) {
        foundContextFiles.push(nestedFile);
        const content = await context.readFile(nestedFile);
        if (content !== null) {
          discoveredFiles.push({
            path: nestedFile,
            size: content.length,
            lineCount: content.split("\n").length,
          });
        }
      }
    }

    if (foundContextFiles.length === 0) {
      findings.push({
        code: "ARI-CTX-001",
        severity: "high",
        pillar: PILLAR,
        message: "No agent context files found (AGENTS.md, CLAUDE.md, .cursorrules, etc.)",
        confidence: "high",
        remediation: {
          action: "create-file",
          path: "AGENTS.md",
          description:
            "Create an AGENTS.md file with project-specific context for AI coding agents",
          estimatedImpact: "+12 points composite",
          confidence: "high",
        },
        evidence: {
          paper: "Lulla et al., 2026",
          finding: "Quality AGENTS.md reduces agent time 28.6%, tokens 16.6%",
          confidence: "high",
        },
      });
    } else {
      // Base score boost for having context files
      score += 15 * Math.min(foundContextFiles.length, 3);

      // Check AGENTS.md quality if it exists
      if (foundContextFiles.includes("AGENTS.md")) {
        const content = await context.readFile("AGENTS.md");
        if (content) {
          const lines = content.split("\n").length;
          const hasHeadings = /^#+\s/m.test(content);
          const hasCodeBlocks = /```/.test(content);
          const hasDontStatements = /\b(don't|do not|never|avoid)\b/i.test(content);

          if (lines < 10) {
            findings.push({
              code: "ARI-CTX-002",
              severity: "medium",
              pillar: PILLAR,
              message:
                "AGENTS.md is too short (< 10 lines). Effective context files provide detailed project-specific guidance.",
              confidence: "medium",
              remediation: {
                action: "modify-config",
                path: "AGENTS.md",
                description:
                  "Expand AGENTS.md with architecture overview, conventions, and common pitfalls",
                confidence: "high",
              },
            });
          } else {
            score += 10;
          }

          if (hasHeadings) score += 5;
          if (hasCodeBlocks) score += 5;
          if (hasDontStatements) score += 5; // Negative instructions are valuable

          // Front-loading check (ARI-CTX-005) for AGENTS.md
          if (lines >= 10 && hasBuriedCriticalInfo(content)) {
            findings.push({
              code: "ARI-CTX-005",
              severity: "medium",
              pillar: PILLAR,
              message:
                "AGENTS.md has critical info (build commands, architecture) buried below the first 20% of the file. Front-load important context for better agent performance.",
              confidence: "medium",
              remediation: {
                action: "modify-config",
                path: "AGENTS.md",
                description:
                  "Move build commands, test commands, and architecture overview to the top of AGENTS.md",
                confidence: "medium",
              },
            });
            score -= 5;
          }

          // Staleness detection (ARI-CTX-006)
          const referencedPaths = extractReferencedPaths(content);
          const fileSet = new Set(context.files);
          const stalePaths: string[] = [];
          for (const rp of referencedPaths) {
            // Check if the referenced path exists as a file or as a directory prefix
            const rpClean = rp.replace(/\/$/, "");
            const existsAsFile = fileSet.has(rpClean);
            const existsAsDir = context.files.some((f) => f.startsWith(rpClean + "/"));
            if (!existsAsFile && !existsAsDir) {
              stalePaths.push(rp);
            }
          }
          if (stalePaths.length > 0) {
            findings.push({
              code: "ARI-CTX-006",
              severity: "low",
              pillar: PILLAR,
              message: `AGENTS.md references ${stalePaths.length} path(s) not found in the repo: ${stalePaths.slice(0, 3).join(", ")}${stalePaths.length > 3 ? "..." : ""}. Content may be stale.`,
              confidence: "medium",
              remediation: {
                action: "modify-config",
                path: "AGENTS.md",
                description:
                  "Review and update AGENTS.md to remove or fix references to non-existent paths",
                confidence: "low",
              },
            });
            score -= 3;
          }

          // Boilerplate detection (ARI-CTX-007)
          if (isLikelyBoilerplate(content, context.files)) {
            findings.push({
              code: "ARI-CTX-007",
              severity: "medium",
              pillar: PILLAR,
              message:
                "AGENTS.md appears to contain auto-generated or boilerplate content without project-specific details.",
              confidence: "low",
              remediation: {
                action: "modify-config",
                path: "AGENTS.md",
                description:
                  "Replace boilerplate content with project-specific architecture, conventions, and build instructions",
                confidence: "medium",
              },
            });
            score -= 10;
          }

          // Conciseness check (ARI-CTX-008)
          if (lines > 500) {
            const codeBlockMatches = content.match(/```/g);
            const codeBlockCount = codeBlockMatches ? Math.floor(codeBlockMatches.length / 2) : 0;
            // Expect roughly 1 code block per 50 lines for well-structured docs
            const expectedBlocks = Math.floor(lines / 50);
            if (codeBlockCount < expectedBlocks / 2) {
              findings.push({
                code: "ARI-CTX-008",
                severity: "low",
                pillar: PILLAR,
                message: `AGENTS.md is very long (${lines} lines) without proportional code examples. Verbose context files can reduce agent efficiency.`,
                confidence: "low",
                remediation: {
                  action: "modify-config",
                  path: "AGENTS.md",
                  description: "Condense AGENTS.md or add more code examples to justify the length",
                  confidence: "medium",
                },
              });
              score -= 5;
            }
          }
        }
      }

      // Front-loading check for CLAUDE.md
      if (foundContextFiles.includes("CLAUDE.md")) {
        const claudeContent = await context.readFile("CLAUDE.md");
        if (claudeContent) {
          const claudeLines = claudeContent.split("\n").length;
          if (claudeLines >= 10 && hasBuriedCriticalInfo(claudeContent)) {
            findings.push({
              code: "ARI-CTX-005",
              severity: "medium",
              pillar: PILLAR,
              message:
                "CLAUDE.md has critical info (build commands, architecture) buried below the first 20% of the file. Front-load important context for better agent performance.",
              confidence: "medium",
              remediation: {
                action: "modify-config",
                path: "CLAUDE.md",
                description:
                  "Move build commands, test commands, and architecture overview to the top of CLAUDE.md",
                confidence: "medium",
              },
            });
            score -= 5;
          }
        }
      }

      // Check for .agentignore
      if (foundContextFiles.includes(".agentignore")) {
        score += 10;
      } else {
        findings.push({
          code: "ARI-CTX-003",
          severity: "low",
          pillar: PILLAR,
          message:
            "No .agentignore file found. This file helps agents exclude irrelevant files from context.",
          confidence: "high",
          remediation: {
            action: "create-file",
            path: ".agentignore",
            description:
              "Create .agentignore to exclude generated files, vendor code, and binaries from agent context",
            confidence: "medium",
          },
        });
      }
    }

    // --- ARI-CTX-009: Non-parsable context file warnings ---
    // Validate parse status for structured context files (JSON, YAML)
    const nonParsableFiles: Array<{ path: string; reason: string }> = [];
    for (const cf of foundContextFiles) {
      const content = await context.readFile(cf);
      if (content === null) continue;

      if (cf.endsWith(".json")) {
        try {
          JSON.parse(content);
        } catch {
          nonParsableFiles.push({ path: cf, reason: "invalid JSON" });
        }
      } else if (cf.endsWith(".yml") || cf.endsWith(".yaml")) {
        const trimmed = content.trim();
        if (trimmed.length === 0) {
          nonParsableFiles.push({ path: cf, reason: "empty YAML file" });
        } else if (/^\t+ /m.test(trimmed) || /^ +\t/m.test(trimmed)) {
          nonParsableFiles.push({ path: cf, reason: "mixed tabs and spaces in YAML" });
        }
      }

      // Check for completely empty files (any type)
      if (content.trim().length === 0 && !cf.endsWith(".yml") && !cf.endsWith(".yaml")) {
        nonParsableFiles.push({ path: cf, reason: "empty file" });
      }
    }

    if (nonParsableFiles.length > 0) {
      score -= 5 * nonParsableFiles.length;
      const details = nonParsableFiles
        .slice(0, 3)
        .map((f) => `${f.path} (${f.reason})`)
        .join(", ");
      findings.push({
        code: "ARI-CTX-009",
        severity: "high",
        pillar: PILLAR,
        message: `${nonParsableFiles.length} context file(s) failed parse validation: ${details}${nonParsableFiles.length > 3 ? ` and ${nonParsableFiles.length - 3} more` : ""}`,
        confidence: "high",
        remediation: {
          action: "modify-config",
          description:
            "Fix parse errors in context files. Invalid JSON or malformed YAML will prevent agents from reading configuration correctly.",
          confidence: "high",
        },
      });
    }

    // --- ARI-CTX-010: Cross-agent compatibility report ---
    const coveredAgents: string[] = [];
    const uncoveredAgents: string[] = [];

    for (const mapping of AGENT_MAPPINGS) {
      const hasFile = mapping.files.some((f) => foundContextFiles.includes(f));
      const hasDir = mapping.dirs?.some((d) => foundContextFiles.includes(d + "/")) ?? false;

      if (hasFile || hasDir) {
        coveredAgents.push(mapping.agent);
      } else {
        uncoveredAgents.push(mapping.agent);
      }
    }

    if (uncoveredAgents.length > 0 && foundContextFiles.length > 0) {
      findings.push({
        code: "ARI-CTX-010",
        severity: "info",
        pillar: PILLAR,
        message: `Agent context coverage: ${coveredAgents.length}/${AGENT_MAPPINGS.length} agents covered. Missing: ${uncoveredAgents.join(", ")}.`,
        confidence: "high",
        remediation: {
          action: "create-file",
          description: `Add context files for uncovered agents: ${uncoveredAgents.join(", ")}. Use AGENTS.md for vendor-neutral context that all agents can read.`,
          confidence: "medium",
        },
      });
    } else if (foundContextFiles.length === 0) {
      findings.push({
        code: "ARI-CTX-010",
        severity: "medium",
        pillar: PILLAR,
        message: `Agent context coverage: 0/${AGENT_MAPPINGS.length} agents covered. No agent has dedicated context files.`,
        confidence: "high",
        remediation: {
          action: "create-file",
          path: "AGENTS.md",
          description:
            "Start with AGENTS.md for vendor-neutral context, then add agent-specific files (CLAUDE.md, .cursorrules, etc.) as needed.",
          confidence: "high",
        },
      });
    }

    // Check README quality as context baseline
    const readme = await context.readFile("README.md");
    if (readme) {
      const readmeLines = readme.split("\n").length;
      if (readmeLines > 20) score += 5;
    } else {
      findings.push({
        code: "ARI-CTX-004",
        severity: "medium",
        pillar: PILLAR,
        message: "No README.md found. README serves as baseline context for all agents.",
        confidence: "high",
        remediation: {
          action: "create-file",
          path: "README.md",
          description:
            "Create a README.md with project overview, setup instructions, and architecture summary",
          confidence: "high",
        },
      });
    }

    // --- Additionality analysis (P1.04) ---
    // Gather reference documents for comparison
    const referenceDocs: Array<{ path: string; content: string }> = [];
    for (const refPath of REFERENCE_DOC_PATHS) {
      const content = await context.readFile(refPath);
      if (content) {
        referenceDocs.push({ path: refPath, content });
      }
    }
    // Gather CI workflow files
    for (const prefix of CI_WORKFLOW_PREFIXES) {
      for (const f of context.files) {
        if (f.startsWith(prefix) && (f.endsWith(".yml") || f.endsWith(".yaml"))) {
          const content = await context.readFile(f);
          if (content) {
            referenceDocs.push({ path: f, content });
          }
        }
      }
    }
    // Include package.json scripts section as reference
    const pkgJson = await context.readJson<{
      description?: string;
      scripts?: Record<string, string>;
    }>("package.json");
    if (pkgJson) {
      const parts: string[] = [];
      if (pkgJson.description) parts.push(pkgJson.description);
      if (pkgJson.scripts) {
        for (const [key, val] of Object.entries(pkgJson.scripts)) {
          parts.push(`${key}: ${val}`);
        }
      }
      if (parts.length > 0) {
        referenceDocs.push({ path: "package.json", content: parts.join("\n") });
      }
    }

    // Run additionality analysis on text-based context files
    const TEXT_CONTEXT_FILES = [
      "AGENTS.md",
      "CLAUDE.md",
      ".cursorrules",
      ".cursor/rules",
      ".github/copilot-instructions.md",
    ];
    const additionalityResults: Array<{
      path: string;
      result: AdditionalityResult;
    }> = [];

    if (referenceDocs.length > 0) {
      for (const cf of foundContextFiles) {
        if (!TEXT_CONTEXT_FILES.includes(cf)) continue;
        const content = await context.readFile(cf);
        if (!content || content.trim().length === 0) continue;

        const result = computeAdditionality(content, cf, referenceDocs);
        additionalityResults.push({ path: cf, result });

        // ARI-CTX-011: High redundancy
        if (result.redundancyPct > 50) {
          const topDuplicates = result.duplicateLines
            .slice(0, 3)
            .map((d) => `L${d.line}: "${d.text}" (similar to ${d.matchedIn})`)
            .join("; ");
          const topAdditive = result.additiveLines
            .slice(0, 3)
            .map((a) => `L${a.line}: "${a.text}"`)
            .join("; ");

          findings.push({
            code: "ARI-CTX-011",
            severity: result.redundancyPct > 70 ? "medium" : "low",
            pillar: PILLAR,
            file: cf,
            message: [
              `${cf} has ${result.redundancyPct.toFixed(1)}% content redundancy with existing repo documentation.`,
              result.methodology,
              topDuplicates ? `Duplicative: ${topDuplicates}.` : "",
              topAdditive ? `Additive: ${topAdditive}.` : "",
            ]
              .filter(Boolean)
              .join(" "),
            confidence: "medium",
            remediation: {
              action: "modify-config",
              path: cf,
              description:
                "Remove content that duplicates README, CONTRIBUTING, or CI config. Focus on project-specific guidance that agents cannot discover through file traversal.",
              estimatedImpact: "+5-10 points composite",
              confidence: "medium",
            },
            evidence: {
              paper: "Gloaguen et al., 2026",
              finding:
                "LLM-generated context files that duplicate README decrease agent success by 2-3% while increasing inference cost by 20%+",
              confidence: "high",
            },
          });

          // Score deduction based on redundancy level
          if (result.redundancyPct > 70) {
            score -= 10;
          } else {
            score -= 5;
          }
        } else if (result.redundancyPct > 30) {
          // Moderate redundancy — info-level finding, minor deduction
          score -= 3;
        }

        // Additionality bonus for high-quality context
        if (result.additionalityPct > 80) {
          score += 5;
        }

        // ARI-CTX-012: LLM-generated file duplicating README
        if (result.redundancyPct > 70 && content && isLikelyBoilerplate(content, context.files)) {
          findings.push({
            code: "ARI-CTX-012",
            severity: "high",
            pillar: PILLAR,
            file: cf,
            message: `${cf} appears to be LLM-generated content that duplicates existing documentation (${result.redundancyPct.toFixed(1)}% redundancy). Auto-generated context files hurt agent performance.`,
            confidence: "medium",
            remediation: {
              action: "modify-config",
              path: cf,
              description:
                "Replace auto-generated content with hand-written, project-specific context. Focus on architecture decisions, conventions, and pitfalls that are not documented elsewhere.",
              estimatedImpact: "+10-15 points composite",
              confidence: "high",
            },
            evidence: {
              paper: "Gloaguen et al., 2026",
              finding:
                "LLM-generated files decrease agent success by 2-3%, human-written files improve by ~4% on niche repos",
              confidence: "high",
            },
          });
          score -= 10; // Additional penalty for LLM-generated duplicate
        }
      }
    }

    // Build summary with file metadata and additionality
    let summary: string;
    if (discoveredFiles.length > 0) {
      const fileDetails = discoveredFiles
        .map((f) =>
          f.size > 0
            ? `${f.path} (${f.lineCount} lines, ${f.size} bytes)`
            : `${f.path} (directory)`,
        )
        .join(", ");
      summary = `Found ${foundContextFiles.length} context file(s): ${fileDetails}`;
      if (additionalityResults.length > 0) {
        const addDetails = additionalityResults
          .map(
            (a) =>
              `${a.path}: ${a.result.additionalityPct.toFixed(1)}% additionality, ${a.result.redundancyPct.toFixed(1)}% redundancy`,
          )
          .join("; ");
        summary += `. Additionality: ${addDetails}`;
      }
    } else {
      summary = "No agent context files found";
    }

    return buildPillarResult(PILLAR, score, "medium", findings, summary, [
      "Lulla et al., 2026 — Quality AGENTS.md reduces agent time 28.6%, tokens 16.6%",
      "GitHub Next, 2024 — Contextual grounding improves Copilot accuracy 30%+",
    ]);
  },
};
