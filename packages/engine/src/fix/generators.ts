    allDeps["pg"] ||
    allDeps["postgres"] ||
    allDeps["@prisma/client"] ||
    allDeps["typeorm"] ||
    allDeps["sequelize"] ||
    allDeps["knex"] ||
    allDeps["drizzle-orm"] ||
    combined.includes("psycopg") ||
    combined.includes("asyncpg") ||
    combined.includes("sqlalchemy") ||
    combined.includes("pgx") ||
    combined.includes("lib/pq") ||
    combined.includes("jackc/pgx")
