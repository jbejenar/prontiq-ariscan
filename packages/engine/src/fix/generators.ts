      seen.add("mongo");
      services.push({
        name: "mongo",
        image: "mongo:7",
        ports: ["27017"],
        environment: ["MONGO_INITDB_ROOT_USERNAME=dev", "MONGO_INITDB_ROOT_PASSWORD=dev"],
        volumes: ["mongodata:/data/db"],
        healthcheck: '["CMD", "mongosh", "--eval", "db.adminCommand({ping:1})"]',
      });
