/**
 * Compute rough overlap between two text strings.
 * Returns fraction (0-1) of lines in `a` that also appear in `b`.
 */
function computeOverlap(a: string, b: string): number {
  const aLines = a.split("\n").filter((l) => l.trim().length > 10);
  if (aLines.length === 0) return 0;

  const bLines = new Set(b.split("\n").map((l) => l.trim()));
  let matches = 0;
  for (const line of aLines) {
    if (bLines.has(line.trim())) matches++;
  }
  return matches / aLines.length;
}
