/**
 * Safe --fix generators (P1.17)
 *
 * All generators are:
 * - Additive-only: create new files, never modify existing ones
 * - Idempotent: running twice produces no additional changes
 * - Non-destructive: existing files are never overwritten
 */

import type { RepoContext } from "../analyzers/analyzer.interface.js";
import type { DetectionResult } from "@prontiq/ariscan-schema";

/** Fix confidence level — determines auto-apply vs suggest-only classification. */
export type FixConfidence = "high" | "medium" | "low";

/** Guided remediation metadata attached to each fix proposal (P2.06). */
export interface TemplateMetadata {
  /** What must be in place before applying this template. */
  prerequisites: string[];
  /** Step-by-step instructions for applying the template. */
  steps: string[];
  /** How to undo the change if something goes wrong. */
  rollbackAdvice: string;
  /** Expected ARI score impact from applying this template. */
  expectedImpact: {
    pillar: string;
    estimatedDelta: string;
  };
}

/** A proposed file change from --fix. */
export interface FixProposal {
  /** Relative path within the repo. */
  path: string;
  /** File content to write. */
  content: string;
  /** Why this file is being generated. */
  rationale: string;
  /** Which ARI criterion this addresses. */
  criterion: string;
  /** Whether the file already exists (skip if true). */
  alreadyExists: boolean;
  /** Confidence level: high = auto-apply, medium = suggest, low = manual review. */
  confidence: FixConfidence;
  /** Guided remediation metadata (P2.06): prerequisites, steps, rollback, impact. */
  metadata: TemplateMetadata;
}

/**
 * Generate all fix proposals for a repository.
 * Returns proposals for files that don't yet exist.
 */
export async function generateFixProposals(
  context: RepoContext,
  detection: DetectionResult | undefined,
): Promise<FixProposal[]> {
  const proposals: FixProposal[] = [];

  const [
    agentsMd,
    agentignore,
    devcontainer,
    providerSkeleton,
    queueProvider,
    emailProvider,
    tsconfigFix,
    nvmrc,
    preCommit,
    codeowners,
    envVarDoc,
    adrTemplate,
    changelogTemplate,
    dockerCompose,
    prTemplate,
    diWiring,
    gitleaks,
    envVarSchema,
  ] = await Promise.all([
    generateAgentsMd(context, detection),
    generateAgentignore(context, detection),
    generateDevcontainer(context, detection),
    generateProviderSkeleton(context, detection),
    generateQueueProvider(context, detection),
    generateEmailProvider(context, detection),
    generateTsconfigStrictness(context, detection),
    generateNvmrc(context, detection),
    generatePreCommitHooks(context, detection),
    generateCodeowners(context),
    generateEnvVarDocumentation(context, detection),
    generateAdrTemplate(context),
    generateChangelogTemplate(context),
    generateDockerCompose(context, detection),
    generatePrTemplate(context),
    generateDiWiringExample(context, detection),
    generateGitleaksConfig(context),
    generateEnvVarSchema(context, detection),
  ]);

  proposals.push(agentsMd, agentignore, devcontainer, providerSkeleton);

  // Conditional proposals: only include if applicable
  for (const fix of [
    queueProvider,
    emailProvider,
    tsconfigFix,
    nvmrc,
    preCommit,
    codeowners,
    envVarDoc,
    adrTemplate,
    changelogTemplate,
    dockerCompose,
    prTemplate,
    diWiring,
    gitleaks,
    envVarSchema,
  ]) {
    if (fix) {
      proposals.push(fix);
    }
  }

  return proposals;
}

/**
 * Generate an AGENTS.md with additive-only content.
 * Per Gloaguen et al. (2026): only include information agents can't discover independently.
 */
async function generateAgentsMd(
  context: RepoContext,
  detection: DetectionResult | undefined,
): Promise<FixProposal> {
  const exists = await context.fileExists("AGENTS.md");

  const agentsMdMetadata: TemplateMetadata = {
    prerequisites: ["Repository has source code and a build system"],
    steps: [
      "Review the generated AGENTS.md file",
      "Fill in TODO sections with project-specific information",
      "Add architecture constraints agents cannot discover from code",
      "Add explicit prohibitions in the 'Do NOT' section",
      "Commit the file to version control",
    ],
    rollbackAdvice: "Delete AGENTS.md — it is a new file with no side effects.",
    expectedImpact: {
      pillar: "P1",
      estimatedDelta: "+10–20 points on Agent Context Quality",
    },
  };

  // Discover existing info to avoid duplication
  const pkgJson = await context.readJson<Record<string, unknown>>("package.json");
  const readme = await context.readFile("README.md");

  const sections: string[] = [];

  sections.push("# AGENTS.md");
  sections.push("");
  sections.push("<!-- Generated by ariscan --fix. Review and customize for your project. -->");
  sections.push("");

  // Build & test commands — only if not obvious from package.json scripts
  sections.push("## Build & Test Commands");
  sections.push("");
  sections.push("<!-- TODO(ARI-CTX-001): Add the exact commands agents should use. -->");
  sections.push("<!-- Only include commands that aren't obvious from package.json/Makefile. -->");
  sections.push("");

  if (pkgJson && typeof pkgJson === "object" && "scripts" in pkgJson) {
    const scripts = pkgJson.scripts as Record<string, string>;
    const commands: string[] = [];
    if (scripts.install || scripts.prepare) commands.push("# install dependencies first");
    if (scripts.build) commands.push(`# build: ${getPackageManager(context)} build`);
    if (scripts.test) commands.push(`# test: ${getPackageManager(context)} test`);
    if (scripts.lint) commands.push(`# lint: ${getPackageManager(context)} lint`);
    if (scripts.typecheck) commands.push(`# typecheck: ${getPackageManager(context)} typecheck`);

    if (commands.length > 0) {
      sections.push("```bash");
      sections.push(...commands);
      sections.push("```");
      sections.push("");
    }
  } else {
    // Non-Node projects: detect from common files
    const hasMakefile = await context.fileExists("Makefile");
    const hasCargoToml = await context.fileExists("Cargo.toml");
    const hasGoMod = await context.fileExists("go.mod");
    const hasPyproject = await context.fileExists("pyproject.toml");

    sections.push("```bash");
    if (hasMakefile) sections.push("# See Makefile for available targets");
    if (hasCargoToml) sections.push("# cargo build && cargo test");
    if (hasGoMod) sections.push("# go build ./... && go test ./...");
    if (hasPyproject) sections.push("# pip install -e . && pytest");
    if (!hasMakefile && !hasCargoToml && !hasGoMod && !hasPyproject) {
      sections.push("# TODO: Add your build and test commands here");
    }
    sections.push("```");
    sections.push("");
  }

  // Architecture constraints — always additive
  sections.push("## Architecture & Constraints");
  sections.push("");
  sections.push(
    "<!-- TODO(ARI-CTX-002): Document constraints agents can't discover from code. -->",
  );
  sections.push("<!-- Examples: -->");
  sections.push('<!-- - "Do NOT use library X because of Y" -->');
  sections.push('<!-- - "Always use the abstraction layer in src/db/, never raw SQL" -->');
  sections.push('<!-- - "Import extensions must use .js for ESM compatibility" -->');
  sections.push("");

  // Language/framework context from detection
  if (detection) {
    const primaryLang = detection.languages.find((l) => l.primary);
    if (primaryLang) {
      sections.push(`Primary language: ${primaryLang.language}`);
    }
    if (detection.frameworks.length > 0) {
      sections.push(`Frameworks: ${detection.frameworks.map((f) => f.framework).join(", ")}`);
    }
    if (detection.monorepo) {
      sections.push(
        `Monorepo: ${detection.monorepo.tool} (${detection.monorepo.packages.length} packages)`,
      );
    }
    sections.push("");
  }

  // Monorepo progressive disclosure (P2.06)
  if (detection?.monorepo) {
    const mono = detection.monorepo;
    sections.push("## Monorepo Structure");
    sections.push("");
    sections.push(`This repository uses **${mono.tool}** with ${mono.packages.length} package(s).`);
    sections.push("");
    sections.push("### Packages");
    sections.push("");
    for (const pkg of mono.packages) {
      sections.push(`- \`${pkg}\``);
    }
    sections.push("");
    sections.push("### Build Order & Dependencies");
    sections.push("");
    sections.push("<!-- TODO(ARI-CTX-002): Document the dependency graph between packages. -->");
    sections.push(
      "<!-- Example: schema -> engine -> cli (engine depends on schema, cli depends on engine) -->",
    );
    sections.push("");
    sections.push("### Package-Level Commands");
    sections.push("");
    sections.push("<!-- TODO(ARI-CTX-002): Add per-package commands if they differ from root. -->");
    sections.push("<!-- Example: -->");
    sections.push(`<!-- - \`${getPackageManager(context)} --filter <pkg-name> test\` -->`);
    sections.push(`<!-- - \`${getPackageManager(context)} --filter <pkg-name> build\` -->`);
    sections.push("");
  }

  // Testing patterns — always useful for agents
  sections.push("## Testing Patterns");
  sections.push("");
  sections.push("<!-- TODO(ARI-TST-001): Document test conventions agents should follow. -->");
  sections.push("<!-- Examples: -->");
  sections.push('<!-- - "Use vitest, not jest" -->');
  sections.push('<!-- - "Mock filesystem via RepoContext, never use real fs in tests" -->');
  sections.push('<!-- - "Test files go in __tests__/ directories" -->');
  sections.push("");

  // Do NOT section — critical for agents
  sections.push("## Do NOT");
  sections.push("");
  sections.push("<!-- TODO(ARI-CTX-003): List explicit prohibitions. -->");
  sections.push("<!-- These are the most valuable instructions for AI agents. -->");
  sections.push("<!-- Examples: -->");
  sections.push("<!-- - Don't use `any` type — use `unknown` with type narrowing -->");
  sections.push("<!-- - Don't import without .js extension -->");
  sections.push("<!-- - Don't add console.log — use the logger -->");
  sections.push("");

  // Check that we're not duplicating README content
  const content = sections.join("\n");
  const readmeDuplication = readme ? computeOverlap(content, readme) : 0;
  if (readmeDuplication > 0.3) {
    // Too much duplication — strip the detected info section
    const filteredSections = sections.filter(
      (s) =>
        !s.startsWith("Primary language:") &&
        !s.startsWith("Frameworks:") &&
        !s.startsWith("Monorepo:"),
    );
    return {
      path: "AGENTS.md",
      content: filteredSections.join("\n"),
      rationale:
        "Provides agent-specific context not discoverable from code. TODOs guide human review.",
      criterion: "ARI-CTX-001",
      alreadyExists: exists,
      confidence: "high" as FixConfidence,
      metadata: agentsMdMetadata,
    };
  }

  return {
    path: "AGENTS.md",
    content,
    rationale:
      "Provides agent-specific context not discoverable from code. TODOs guide human review.",
    criterion: "ARI-CTX-001",
    alreadyExists: exists,
    confidence: "high" as FixConfidence,
    metadata: agentsMdMetadata,
  };
}

/**
 * Generate an .agentignore file with sensible defaults.
 */
async function generateAgentignore(
  context: RepoContext,
  detection: DetectionResult | undefined,
): Promise<FixProposal> {
  const exists = await context.fileExists(".agentignore");

  const lines: string[] = [];
  lines.push("# .agentignore — Files excluded from AI agent context");
  lines.push("# Generated by ariscan --fix. Customize for your project.");
  lines.push("# Syntax: .gitignore-compatible glob patterns");
  lines.push("");

  // Universal patterns
  lines.push("# Build artifacts");
  lines.push("dist/");
  lines.push("build/");
  lines.push(".next/");
  lines.push("out/");
  lines.push(".turbo/");
  lines.push("");

  lines.push("# Dependencies");
  lines.push("node_modules/");
  lines.push("vendor/");
  lines.push(".venv/");
  lines.push("__pycache__/");
  lines.push("");

  lines.push("# Lockfiles (high token cost, low agent value)");
  lines.push("package-lock.json");
  lines.push("pnpm-lock.yaml");
  lines.push("yarn.lock");
  lines.push("Cargo.lock");
  lines.push("go.sum");
  lines.push("poetry.lock");
  lines.push("composer.lock");
  lines.push("");

  lines.push("# Generated files");
  lines.push("*.generated.*");
  lines.push("*.min.js");
  lines.push("*.min.css");
  lines.push("*.map");
  lines.push("*.d.ts");
  lines.push("");

  lines.push("# Coverage & reports");
  lines.push("coverage/");
  lines.push(".nyc_output/");
  lines.push("htmlcov/");
  lines.push("");

  lines.push("# IDE & editor");
  lines.push(".idea/");
  lines.push("*.swp");
  lines.push("*.swo");
  lines.push("");

  // Language-specific patterns
  const primaryLang = detection?.languages.find((l) => l.primary);
  if (primaryLang) {
    switch (normalizeLang(primaryLang.language)) {
      case "python":
        lines.push("# Python-specific");
        lines.push("*.pyc");
        lines.push("*.egg-info/");
        lines.push(".tox/");
        lines.push(".mypy_cache/");
        lines.push("");
        break;
      case "go":
        lines.push("# Go-specific");
        lines.push("*.test");
        lines.push("");
        break;
      case "rust":
        lines.push("# Rust-specific");
        lines.push("target/");
        lines.push("");
        break;
      case "java":
        lines.push("# Java-specific");
        lines.push("*.class");
        lines.push("target/");
        lines.push(".gradle/");
        lines.push("");
        break;
    }
  }

  return {
    path: ".agentignore",
    content: lines.join("\n"),
    rationale: "Excludes high-token, low-value files from agent context to reduce inference cost.",
    criterion: "ARI-CTX-004",
    alreadyExists: exists,
    confidence: "high" as FixConfidence,
    metadata: {
      prerequisites: ["Repository uses AI coding agents"],
      steps: [
        "Review the generated .agentignore file",
        "Add project-specific patterns for large generated files",
        "Remove patterns for files agents should see",
        "Commit the file to version control",
      ],
      rollbackAdvice: "Delete .agentignore — agents will see all files again.",
      expectedImpact: {
        pillar: "P1",
        estimatedDelta: "+5–10 points on Agent Context Quality",
      },
    },
  };
}

